test('step 8: only world B changes with its work spot, and a quiet pocket is optional', async ({ page }) => {
  await page.goto(base + slugs[7])
  const log = page.getByRole('log', { name: 'Change log' })
  await expect(log).toContainText('Nothing has changed yet')
  await page.waitForTimeout(400)
  await page.screenshot({ path: 'artifacts/lesson08/step08-start.png' })
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(log).toContainText('reaches pocket', { timeout: 20000 })
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const paused = await log.innerText()
  await page.waitForTimeout(600)
  expect(await log.innerText()).toBe(paused)
  expect(paused).not.toContain('A ·')
  expect(paused).toContain('B ·')
  await expect(page.getByRole('group', { name: 'World B' })).toContainText('staying put')
  await page.screenshot({ path: 'artifacts/lesson08/step08-near-end.png' })
  const before = await page.locator('.branching-world').first().innerText()
  await page.getByLabel('Noise overlay').uncheck()
  expect(await page.locator('.branching-world').first().innerText()).toBe(before)
  await page.screenshot({ path: 'artifacts/lesson08/step08-no-overlay.png' })
  await page.getByLabel('Noise overlay').check()
  await page.getByRole('button', { name: 'Sync Reset' }).click()
  await expect(log).toContainText('Nothing has changed yet')
  await page.getByLabel('Work in world B').selectOption('Far end')
  await page.getByRole('button', { name: 'Step' }).click()
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await page.waitForTimeout(6000)
  await expect(log).toContainText('Nothing has changed yet')
  await page.getByLabel('Work in world B').selectOption('Near the residents')
  await page.getByLabel('Quiet pockets').selectOption('None')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(log).toContainText('no pocket has room', { timeout: 15000 })
  await page.screenshot({ path: 'artifacts/lesson08/step08-no-pockets.png' })
  await page.getByRole('button', { name: 'Restore Example' }).click()
  await expect(page.getByLabel('Quiet pockets')).toHaveValue('Open')
  await expect(page.getByLabel('Work in world B')).toHaveValue('Near the residents')
})
