test('step 2: F counts double each generation and the previous drawing underlays', async ({ page }) => {
  await page.goto(base + slugs[1])
  const next = page.getByRole('button', { name: 'Next Generation' })
  const counts = []
  for (let generation = 0; generation <= 4; generation += 1) {
    await expect(status(page)).toContainText(`Generation ${generation} ·`)
    counts.push(Number((await status(page).innerText()).match(/· (\d+) F/)[1]))
    if (generation === 3) { await page.waitForTimeout(300); await page.screenshot({ path: 'artifacts/lesson08/step02-generation3.png' }) }
    if (generation < 4) await next.click()
  }
  expect(counts).toEqual([1, 2, 4, 8, 16])
  await expect(next).toBeDisabled()
  await page.screenshot({ path: 'artifacts/lesson08/step02-generation4.png' })
  await page.getByRole('button', { name: 'Back to axiom' }).click()
  await expect(status(page)).toContainText('Generation 0 · 1 symbols')
})

