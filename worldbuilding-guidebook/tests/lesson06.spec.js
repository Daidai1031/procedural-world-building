  await page.getByLabel('Body radius').fill('0.5')
  await expect(page.locator('.path-status')).toContainText('Blocked')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  await expect(page.locator('.path-tick')).toContainText('Waiting', { timeout: 10000 })
