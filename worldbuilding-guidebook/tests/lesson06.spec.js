  await page.getByLabel('Passage state').selectOption('Open passage')
  await expect(page.locator('.path-status')).toContainText('Passable')
  await page.locator('.path-inspect summary').click()
  await page.getByLabel('Show terrain experiment').check()
  await page.getByLabel('Terrain effect').selectOption('After')
  await page.getByLabel('Corridor width').fill('1.5')
  await expect(page.locator('.path-status')).toContainText('After terrain edit')
